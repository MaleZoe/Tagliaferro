-- Agrega gestión interna de proyectos, fases, tareas e historial de cambios.
-- La migración es aditiva, no contiene datos simulados y no se ejecuta automáticamente.

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) between 2 and 160),
  description text not null default '',
  objective text not null default '',
  owner_id uuid not null references auth.users(id),
  created_by uuid not null references auth.users(id),
  start_date date,
  due_date date,
  priority text not null default 'media' check (priority in ('baja', 'media', 'alta', 'urgente')),
  status text not null default 'planificacion' check (status in ('planificacion', 'pendiente', 'en_curso', 'pausado', 'completado', 'cancelado')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (due_date is null or start_date is null or due_date >= start_date)
);

create table if not exists public.project_phases (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  name text not null check (length(trim(name)) between 2 and 160),
  description text not null default '',
  start_date date,
  due_date date,
  position integer not null default 0,
  created_at timestamptz not null default now(),
  check (due_date is null or start_date is null or due_date >= start_date)
);

create table if not exists public.project_tasks (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  phase_id bigint references public.project_phases(id) on delete set null,
  title text not null check (length(trim(title)) between 2 and 200),
  description text not null default '',
  assignee_id uuid references auth.users(id),
  due_date date,
  priority text not null default 'media' check (priority in ('baja', 'media', 'alta', 'urgente')),
  status text not null default 'pendiente' check (status in ('pendiente', 'en_curso', 'bloqueada', 'completada')),
  observations text not null default '',
  completed_at timestamptz,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.project_history (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  task_id bigint references public.project_tasks(id) on delete set null,
  actor_id uuid not null references auth.users(id),
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists projects_owner_status_idx on public.projects(owner_id, status);
create index if not exists project_tasks_assignee_status_idx on public.project_tasks(assignee_id, status);
create index if not exists project_tasks_due_status_idx on public.project_tasks(due_date, status);
create index if not exists project_phases_project_position_idx on public.project_phases(project_id, position);
create index if not exists project_history_project_created_idx on public.project_history(project_id, created_at desc);

-- El backend es el único escritor/lector de estos registros y aplica el rol de cada sesión.
alter table public.projects enable row level security;
alter table public.project_phases enable row level security;
alter table public.project_tasks enable row level security;
alter table public.project_history enable row level security;
revoke all on table public.projects, public.project_phases, public.project_tasks, public.project_history from anon, authenticated;
