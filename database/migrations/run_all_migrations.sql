create or replace function public.register_inventory_movement(
  p_variant_id integer,
  p_delta integer,
  p_reason text,
  p_responsible_id uuid
) returns table (movement_id bigint, stock_before integer, stock_after integer)
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_before integer;
  v_after integer;
  v_movement_id bigint;
begin
  if p_variant_id is null or p_delta is null or p_delta = 0 or p_responsible_id is null
     or length(trim(coalesce(p_reason, ''))) < 3 or length(trim(p_reason)) > 500 then
    raise exception 'El ajuste y el motivo deben ser válidos' using errcode = '22023';
  end if;

  select stock into v_before from public.product_variants where id = p_variant_id for update;
  if not found then raise exception 'Variante inexistente' using errcode = 'P0002'; end if;
  v_after := v_before + p_delta;
  if v_after < 0 then raise exception 'Stock insuficiente para esta salida' using errcode = '23514'; end if;

  update public.product_variants set stock = v_after where id = p_variant_id;
  insert into public.inventory_movements(variant_id, cantidad, motivo, responsable_id, stock_anterior, stock_actual)
  values (p_variant_id, p_delta, trim(p_reason), p_responsible_id, v_before, v_after)
  returning id into v_movement_id;
  return query select v_movement_id, v_before, v_after;
end;
$$;

create or replace function public.create_product_variant(
  p_product_id integer,
  p_size text,
  p_initial_stock integer,
  p_minimum integer,
  p_responsible_id uuid
) returns table (variant_id integer, stock_after integer)
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_variant_id integer;
  v_stock integer := 0;
begin
  if p_product_id is null or p_responsible_id is null or length(trim(coalesce(p_size, ''))) not between 1 and 40
     or p_initial_stock is null or p_initial_stock < 0 or p_initial_stock > 100000
     or p_minimum is null or p_minimum < 0 or p_minimum > 100000 then
    raise exception 'Variante o existencias iniciales inválidas' using errcode = '22023';
  end if;
  perform 1 from public.products where id = p_product_id and activo = true for update;
  if not found then raise exception 'Producto inexistente o inactivo' using errcode = 'P0002'; end if;
  if exists (select 1 from public.product_variants where product_id = p_product_id and lower(talle) = lower(trim(p_size))) then
    raise exception 'Ese talle ya existe para el producto' using errcode = '23505';
  end if;
  insert into public.product_variants(product_id, talle, stock, stock_minimo)
  values (p_product_id, trim(p_size), 0, p_minimum)
  returning id into v_variant_id;
  if p_initial_stock > 0 then
    select movement.stock_after into v_stock from public.register_inventory_movement(
      v_variant_id, p_initial_stock, 'Stock inicial', p_responsible_id
    ) as movement;
  end if;
  return query select v_variant_id, v_stock;
end;
$$;

create or replace function public.register_pos_sale(
  p_request_key uuid,
  p_employee_id uuid,
  p_payment_method text,
  p_items jsonb
) returns table (sale_id bigint, total numeric, repeated boolean)
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_sale_id bigint;
  v_existing_employee uuid;
  v_total numeric(12,2) := 0;
  v_item record;
  v_name text;
  v_size text;
  v_price numeric(12,2);
  v_stock integer;
  v_after integer;
begin
  if p_request_key is null or p_employee_id is null or p_items is null
     or p_payment_method is null or p_payment_method not in ('efectivo', 'tarjeta', 'transferencia', 'otro')
     or jsonb_typeof(p_items) is distinct from 'array' then
    raise exception 'La venta tiene datos inválidos' using errcode = '22023';
  end if;
  if jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 50 then
    raise exception 'La venta debe incluir entre 1 y 50 líneas' using errcode = '22023';
  end if;

  insert into public.sales(request_key, employee_id, payment_method, total)
  values (p_request_key, p_employee_id, p_payment_method, 0)
  on conflict (request_key) do nothing
  returning id into v_sale_id;
  if v_sale_id is null then
    select id, employee_id, sales.total into v_sale_id, v_existing_employee, v_total
      from public.sales where request_key = p_request_key;
    if v_existing_employee <> p_employee_id then raise exception 'Clave de operación no autorizada' using errcode = '42501'; end if;
    return query select v_sale_id, v_total, true;
    return;
  end if;

  for v_item in
    select variant_id, sum(quantity)::integer as quantity
      from jsonb_to_recordset(p_items) as item(variant_id integer, quantity integer)
     group by variant_id order by variant_id
  loop
    if v_item.variant_id is null or v_item.quantity is null or v_item.quantity < 1 or v_item.quantity > 100 then
      raise exception 'Variante o cantidad inválida' using errcode = '22023';
    end if;

    select p.nombre, v.talle, p.precio, v.stock
      into v_name, v_size, v_price, v_stock
      from public.product_variants v
      join public.products p on p.id = v.product_id
     where v.id = v_item.variant_id and p.activo = true
     for update of v, p;
    if not found then raise exception 'Producto o variante no disponible' using errcode = 'P0002'; end if;
    if v_stock < v_item.quantity then raise exception 'Stock insuficiente para completar la venta' using errcode = '23514'; end if;

    v_after := v_stock - v_item.quantity;
    update public.product_variants set stock = v_after where id = v_item.variant_id;
    insert into public.sale_items(sale_id, variant_id, product_name, size, quantity, unit_price, line_total)
    values (v_sale_id, v_item.variant_id, v_name, v_size, v_item.quantity, v_price, v_price * v_item.quantity);
    insert into public.inventory_movements(variant_id, cantidad, motivo, responsable_id, stock_anterior, stock_actual, sale_id)
    values (v_item.variant_id, -v_item.quantity, 'Venta presencial #' || v_sale_id, p_employee_id, v_stock, v_after, v_sale_id);
    v_total := v_total + v_price * v_item.quantity;
  end loop;

  update public.sales set total = v_total where id = v_sale_id;
  return query select v_sale_id, v_total, false;
end;
$$;

create or replace function public.register_pos_sale_v2(
  p_request_key uuid, p_employee_id uuid, p_items jsonb, p_payment_lines jsonb,
  p_discount numeric, p_cash_session_id bigint
) returns table (sale_id bigint, total numeric, repeated boolean)
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_sale_id bigint; v_gross numeric(12,2); v_net numeric(12,2); v_repeated boolean;
  v_method_count integer; v_single_method text; v_paid numeric(12,2); v_line record;
begin
  if p_employee_id is null or p_request_key is null or jsonb_typeof(p_payment_lines) is distinct from 'array'
     or jsonb_array_length(p_payment_lines) not between 1 and 4 or p_discount is null or p_discount < 0 or p_discount > 100000000 then
    raise exception 'Datos de cobro inválidos' using errcode = '22023';
  end if;
  if exists (
    select 1 from jsonb_to_recordset(p_payment_lines) as x(method text, amount numeric)
     where method not in ('efectivo', 'tarjeta', 'transferencia', 'otro') or amount is null or amount <= 0 or amount > 1000000000
  ) then raise exception 'Detalle de pagos inválido' using errcode = '22023'; end if;
  if (select count(distinct method) from jsonb_to_recordset(p_payment_lines) as x(method text, amount numeric))
     <> (select count(*) from jsonb_to_recordset(p_payment_lines) as x(method text, amount numeric)) then
    raise exception 'No repitas el mismo medio de pago' using errcode = '22023';
  end if;
  perform 1 from public.cash_sessions where id = p_cash_session_id and status = 'abierta' for update;
  if not found then raise exception 'Abrí una caja antes de registrar ventas' using errcode = '23514'; end if;

  select s.id, s.total, true into v_sale_id, v_gross, v_repeated from public.sales s where s.request_key = p_request_key;
  if v_sale_id is not null then
    if (select employee_id from public.sales where id = v_sale_id) <> p_employee_id then raise exception 'Clave de operación no autorizada' using errcode = '42501'; end if;
    return query select v_sale_id, v_gross, true;
    return;
  end if;
  select result.sale_id, result.total, result.repeated into v_sale_id, v_gross, v_repeated
    from public.register_pos_sale(p_request_key, p_employee_id, 'otro', p_items) as result;
  if v_repeated then return query select v_sale_id, v_gross, true; return; end if;
  if p_discount > v_gross then raise exception 'El descuento supera el importe de la venta' using errcode = '22023'; end if;
  v_net := v_gross - p_discount;
  select coalesce(sum(amount), 0)::numeric(12,2), count(distinct method), min(method)
    into v_paid, v_method_count, v_single_method
    from jsonb_to_recordset(p_payment_lines) as x(method text, amount numeric);
  if v_net <= 0 or v_paid <> v_net then raise exception 'Los pagos deben cubrir exactamente el total final' using errcode = '22023'; end if;
  update public.sales set total = v_net, discount = p_discount, cash_session_id = p_cash_session_id,
    payment_method = case when v_method_count = 1 then v_single_method else 'otro' end where id = v_sale_id;
  for v_line in select method, amount from jsonb_to_recordset(p_payment_lines) as x(method text, amount numeric)
  loop insert into public.sale_payments(sale_id, method, amount) values (v_sale_id, v_line.method, v_line.amount); end loop;
  return query select v_sale_id, v_net, false;
end;
$$;

create or replace function public.create_admin_product(
  p_name text, p_description text, p_price numeric, p_sport_slug text, p_image_url text,
  p_sku text, p_size text, p_color text, p_initial_stock integer, p_minimum integer, p_responsible_id uuid
) returns table (product_id integer, variant_id integer)
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_sport_column text;
  v_product_id integer;
  v_variant_id integer;
begin
  if p_responsible_id is null or length(trim(coalesce(p_name, ''))) not between 2 and 200
     or length(coalesce(p_description, '')) > 4000 or p_price is null or p_price <= 0 or p_price > 100000000
     or length(trim(coalesce(p_sport_slug, ''))) not between 1 and 80
     or length(coalesce(p_image_url, '')) > 1000 or length(coalesce(p_sku, '')) > 100
     or length(trim(coalesce(p_size, ''))) not between 1 and 40 or length(coalesce(p_color, '')) > 60
     or p_initial_stock is null or p_initial_stock < 0 or p_initial_stock > 100000
     or p_minimum is null or p_minimum < 0 or p_minimum > 100000 then
    raise exception 'Datos de producto o variante inválidos' using errcode = '22023';
  end if;

  select a.attname into v_sport_column
    from pg_constraint c
    cross join lateral unnest(c.conkey) as key_column(attnum)
    join pg_attribute a on a.attrelid = c.conrelid and a.attnum = key_column.attnum
   where c.contype = 'f' and c.conrelid = 'public.products'::regclass
     and c.confrelid = 'public.sports'::regclass
   limit 1;

  v_sport_column := coalesce(v_sport_column, 'sport_id');

  if not exists (select 1 from public.sports where slug = trim(p_sport_slug)) then
    raise exception 'El deporte no existe' using errcode = '23503';
  end if;
  if p_sku is not null and length(trim(p_sku)) > 0 and exists (select 1 from public.products where lower(sku) = lower(trim(p_sku))) then
    raise exception 'El SKU ya está en uso' using errcode = '23505';
  end if;

  execute format(
    'insert into public.products(nombre, descripcion, precio, imagen_url, activo, sku, %I)
     select $1, $2, $3, $4, true, nullif($5, ''''), id from public.sports where slug = $6 returning id',
    v_sport_column
  ) into v_product_id using trim(p_name), coalesce(p_description, ''), p_price, coalesce(p_image_url, ''), p_sku, trim(p_sport_slug);

  if v_product_id is null then raise exception 'No se pudo asociar el producto al deporte' using errcode = '23503'; end if;

  select variant_id into v_variant_id from public.create_product_variant(
    v_product_id, trim(p_size), p_initial_stock, p_minimum, p_responsible_id
  );
  if nullif(trim(coalesce(p_color, '')), '') is not null then
    update public.product_variants set color = trim(p_color) where id = v_variant_id;
  end if;
  return query select v_product_id, v_variant_id;
end;
$$;

create or replace function public.create_product_variant_color(
  p_product_id integer, p_size text, p_color text, p_initial_stock integer, p_minimum integer, p_responsible_id uuid
) returns table (variant_id integer, stock_after integer)
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_variant_id integer; v_stock integer := 0;
begin
  if p_product_id is null or p_responsible_id is null or length(trim(coalesce(p_size, ''))) not between 1 and 40
     or length(coalesce(p_color, '')) > 60 or p_initial_stock is null or p_initial_stock < 0 or p_initial_stock > 100000
     or p_minimum is null or p_minimum < 0 or p_minimum > 100000 then
    raise exception 'Variante o existencias iniciales inválidas' using errcode = '22023';
  end if;
  perform 1 from public.products where id = p_product_id and activo = true for update;
  if not found then raise exception 'Producto inexistente o inactivo' using errcode = 'P0002'; end if;
  if exists (select 1 from public.product_variants where product_id = p_product_id and lower(talle) = lower(trim(p_size)) and lower(color) = lower(trim(coalesce(p_color, '')))) then
    raise exception 'La combinación de talle y color ya existe' using errcode = '23505';
  end if;
  insert into public.product_variants(product_id, talle, color, stock, stock_minimo)
  values (p_product_id, trim(p_size), trim(coalesce(p_color, '')), 0, p_minimum) returning id into v_variant_id;
  if p_initial_stock > 0 then
    select movement.stock_after into v_stock from public.register_inventory_movement(v_variant_id, p_initial_stock, 'Stock inicial', p_responsible_id) as movement;
  end if;
  return query select v_variant_id, v_stock;
end;
$$;

create or replace function public.open_cash_session(p_user_id uuid, p_opening_float numeric)
returns public.cash_sessions language plpgsql security definer set search_path = public, pg_temp as $$
declare v_session public.cash_sessions;
begin
  if p_user_id is null or p_opening_float is null or p_opening_float < 0 or p_opening_float > 1000000000 then
    raise exception 'Saldo inicial inválido' using errcode = '22023';
  end if;
  insert into public.cash_sessions(opened_by, opening_float) values (p_user_id, p_opening_float) returning * into v_session;
  return v_session;
end;
$$;

create or replace function public.register_cash_movement(p_session_id bigint, p_kind text, p_amount numeric, p_reason text, p_user_id uuid)
returns public.cash_movements language plpgsql security definer set search_path = public, pg_temp as $$
declare v_movement public.cash_movements;
begin
  if p_session_id is null or p_kind not in ('entrada', 'retiro') or p_amount is null or p_amount <= 0 or p_amount > 1000000000
     or p_user_id is null or length(trim(coalesce(p_reason, ''))) not between 3 and 500 then
    raise exception 'Movimiento de caja inválido' using errcode = '22023';
  end if;
  perform 1 from public.cash_sessions where id = p_session_id and status = 'abierta' for update;
  if not found then raise exception 'La caja no está abierta' using errcode = '23514'; end if;
  insert into public.cash_movements(session_id, kind, amount, reason, responsible_id)
  values (p_session_id, p_kind, p_amount, trim(p_reason), p_user_id) returning * into v_movement;
  return v_movement;
end;
$$;

create or replace function public.close_cash_session(p_session_id bigint, p_user_id uuid, p_counted_cash numeric)
returns public.cash_sessions language plpgsql security definer set search_path = public, pg_temp as $$
declare v_session public.cash_sessions; v_expected numeric(12,2);
begin
  if p_session_id is null or p_user_id is null or p_counted_cash is null or p_counted_cash < 0 or p_counted_cash > 1000000000 then
    raise exception 'Cierre de caja inválido' using errcode = '22023';
  end if;
  select * into v_session from public.cash_sessions where id = p_session_id and status = 'abierta' for update;
  if not found then raise exception 'La caja no está abierta' using errcode = '23514'; end if;
  select v_session.opening_float
    + coalesce((select sum(p.amount) from public.sales s join public.sale_payments p on p.sale_id = s.id where s.cash_session_id = p_session_id and s.status = 'completada' and p.method = 'efectivo'), 0)
    + coalesce((select sum(case when m.kind = 'entrada' then m.amount else -m.amount end) from public.cash_movements m where m.session_id = p_session_id), 0)
    into v_expected;
  update public.cash_sessions set status = 'cerrada', closed_by = p_user_id, closed_at = now(),
    expected_cash = v_expected, counted_cash = p_counted_cash, difference = p_counted_cash - v_expected
   where id = p_session_id returning * into v_session;
  return v_session;
end;
$$;

create or replace function public.register_purchase_receipt(p_supplier_id bigint, p_reference text, p_notes text, p_user_id uuid, p_items jsonb)
returns table (receipt_id bigint, item_count integer) language plpgsql security definer set search_path = public, pg_temp as $$
declare v_receipt_id bigint; v_item record; v_before integer; v_after integer; v_count integer := 0;
begin
  if p_supplier_id is null or p_user_id is null or jsonb_typeof(p_items) is distinct from 'array'
     or jsonb_array_length(p_items) not between 1 and 100 or length(coalesce(p_reference, '')) > 120 or length(coalesce(p_notes, '')) > 1000 then
    raise exception 'Reposición inválida' using errcode = '22023';
  end if;
  perform 1 from public.suppliers where id = p_supplier_id and activo = true for update;
  if not found then raise exception 'Proveedor inexistente o inactivo' using errcode = 'P0002'; end if;
  insert into public.purchase_receipts(supplier_id, reference, notes, responsible_id)
  values (p_supplier_id, coalesce(trim(p_reference), ''), coalesce(trim(p_notes), ''), p_user_id) returning id into v_receipt_id;
  for v_item in select variant_id, quantity, unit_cost from jsonb_to_recordset(p_items) as x(variant_id integer, quantity integer, unit_cost numeric) order by variant_id
  loop
    if v_item.variant_id is null or v_item.quantity is null or v_item.quantity < 1 or v_item.quantity > 100000 or v_item.unit_cost is null or v_item.unit_cost < 0 then
      raise exception 'Línea de reposición inválida' using errcode = '22023';
    end if;
    select stock into v_before from public.product_variants where id = v_item.variant_id for update;
    if not found then raise exception 'Variante inexistente' using errcode = 'P0002'; end if;
    v_after := v_before + v_item.quantity;
    update public.product_variants set stock = v_after where id = v_item.variant_id;
    insert into public.purchase_receipt_items(receipt_id, variant_id, quantity, unit_cost) values (v_receipt_id, v_item.variant_id, v_item.quantity, v_item.unit_cost);
    insert into public.inventory_movements(variant_id, cantidad, motivo, responsable_id, stock_anterior, stock_actual, supplier_id, receipt_id)
    values (v_item.variant_id, v_item.quantity, 'Reposición ' || coalesce(trim(p_reference), '#' || v_receipt_id), p_user_id, v_before, v_after, p_supplier_id, v_receipt_id);
    v_count := v_count + 1;
  end loop;
  return query select v_receipt_id, v_count;
end;
$$;

create or replace function public.reverse_pos_sale(
  p_sale_id bigint,
  p_responsible_id uuid,
  p_new_status text,
  p_reason text
) returns table (sale_id bigint, status text, repeated boolean)
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_status text;
  v_item record;
  v_before integer;
  v_after integer;
begin
  if p_new_status is null or p_new_status not in ('anulada', 'devuelta') or p_responsible_id is null
     or length(trim(coalesce(p_reason, ''))) < 3 or length(trim(p_reason)) > 500 then
    raise exception 'La reversión requiere un estado y motivo válidos' using errcode = '22023';
  end if;
  select sales.status into v_status from public.sales where id = p_sale_id for update;
  if not found then raise exception 'Venta inexistente' using errcode = 'P0002'; end if;
  if v_status = p_new_status then return query select p_sale_id, v_status, true; return; end if;
  if v_status <> 'completada' then raise exception 'La venta ya fue revertida' using errcode = '23514'; end if;

  for v_item in select variant_id, quantity from public.sale_items where sale_items.sale_id = p_sale_id order by variant_id
  loop
    select stock into v_before from public.product_variants where id = v_item.variant_id for update;
    if not found then raise exception 'Variante inexistente' using errcode = 'P0002'; end if;
    v_after := v_before + v_item.quantity;
    update public.product_variants set stock = v_after where id = v_item.variant_id;
    insert into public.inventory_movements(variant_id, cantidad, motivo, responsable_id, stock_anterior, stock_actual, sale_id)
    values (v_item.variant_id, v_item.quantity, initcap(p_new_status) || ' de venta #' || p_sale_id || ': ' || trim(p_reason), p_responsible_id, v_before, v_after, p_sale_id);
  end loop;
  update public.sales set status = p_new_status where id = p_sale_id;
  return query select p_sale_id, p_new_status, false;
end;
$$;

create or replace function public.reverse_pos_sale_v2(p_sale_id bigint, p_responsible_id uuid, p_new_status text, p_reason text)
returns table (sale_id bigint, status text, repeated boolean)
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_sale_status text; v_cash_refund numeric(12,2); v_result record; v_open_session bigint;
begin
  select sales.status into v_sale_status from public.sales where sales.id = p_sale_id for update;
  if not found then raise exception 'Venta inexistente' using errcode = 'P0002'; end if;
  if v_sale_status = p_new_status then return query select p_sale_id, v_sale_status, true; return; end if;
  if v_sale_status <> 'completada' then raise exception 'La venta ya fue revertida' using errcode = '23514'; end if;
  select coalesce(sum(amount), 0) into v_cash_refund from public.sale_payments where sale_id = p_sale_id and method = 'efectivo';
  if v_cash_refund > 0 then
    select id into v_open_session from public.cash_sessions where status = 'abierta' order by opened_at desc limit 1 for update;
    if v_open_session is null then raise exception 'Abrí una caja para registrar la devolución en efectivo' using errcode = '23514'; end if;
  end if;
  select * into v_result from public.reverse_pos_sale(p_sale_id, p_responsible_id, p_new_status, p_reason);
  if not v_result.repeated and v_cash_refund > 0 then
    insert into public.cash_movements(session_id, kind, amount, reason, sale_id, responsible_id)
    values (v_open_session, 'devolucion', v_cash_refund, 'Devolución en efectivo de venta #' || p_sale_id || ': ' || trim(p_reason), p_sale_id, p_responsible_id);
  end if;
  return query select v_result.sale_id, v_result.status, v_result.repeated;
end;
$$;

