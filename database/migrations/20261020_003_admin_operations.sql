alter table public.products add column if not exists sku text;
alter table public.product_variants add column if not exists color text not null default '';
create unique index if not exists products_sku_unique_idx on public.products (lower(sku)) where sku is not null and length(trim(sku)) > 0;
create unique index if not exists product_variants_product_size_color_idx
  on public.product_variants (product_id, lower(talle), lower(color));

create table if not exists public.suppliers (
  id bigint generated by default as identity primary key,
  nombre text not null check (length(trim(nombre)) between 2 and 160),
  contacto text not null default '',
  email text not null default '',
  telefono text not null default '',
  direccion text not null default '',
  observaciones text not null default '',
  activo boolean not null default true,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists suppliers_name_active_idx on public.suppliers (lower(nombre), activo);

create table if not exists public.supplier_products (
  supplier_id bigint not null references public.suppliers(id),
  product_id integer not null references public.products(id),
  supplier_sku text not null default '',
  unit_cost numeric(12,2) check (unit_cost is null or unit_cost >= 0),
  updated_at timestamptz not null default now(),
  primary key (supplier_id, product_id)
);

create table if not exists public.purchase_receipts (
  id bigint generated by default as identity primary key,
  supplier_id bigint not null references public.suppliers(id),
  reference text not null default '',
  notes text not null default '',
  responsible_id uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);
create table if not exists public.purchase_receipt_items (
  id bigint generated by default as identity primary key,
  receipt_id bigint not null references public.purchase_receipts(id),
  variant_id integer not null references public.product_variants(id),
  quantity integer not null check (quantity > 0),
  unit_cost numeric(12,2) not null check (unit_cost >= 0)
);
create index if not exists purchase_receipts_supplier_created_idx on public.purchase_receipts(supplier_id, created_at desc);
create index if not exists purchase_receipt_items_variant_idx on public.purchase_receipt_items(variant_id);

create table if not exists public.cash_sessions (
  id bigint generated by default as identity primary key,
  opened_by uuid not null references auth.users(id),
  opened_at timestamptz not null default now(),
  opening_float numeric(12,2) not null check (opening_float >= 0),
  status text not null default 'abierta' check (status in ('abierta', 'cerrada')),
  closed_by uuid references auth.users(id),
  closed_at timestamptz,
  expected_cash numeric(12,2),
  counted_cash numeric(12,2),
  difference numeric(12,2),
  check ((status = 'abierta' and closed_at is null and closed_by is null) or (status = 'cerrada' and closed_at is not null and closed_by is not null))
);
create unique index if not exists cash_sessions_single_open_idx on public.cash_sessions ((status)) where status = 'abierta';
create index if not exists cash_sessions_opened_at_idx on public.cash_sessions(opened_at desc);

create table if not exists public.sale_payments (
  id bigint generated by default as identity primary key,
  sale_id bigint not null references public.sales(id),
  method text not null check (method in ('efectivo', 'tarjeta', 'transferencia', 'otro')),
  amount numeric(12,2) not null check (amount > 0),
  created_at timestamptz not null default now()
);
create index if not exists sale_payments_sale_idx on public.sale_payments(sale_id);
alter table public.sales add column if not exists discount numeric(12,2) not null default 0 check (discount >= 0);
alter table public.sales add column if not exists cash_session_id bigint references public.cash_sessions(id);

create table if not exists public.cash_movements (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.cash_sessions(id),
  kind text not null check (kind in ('entrada', 'retiro', 'devolucion')),
  amount numeric(12,2) not null check (amount > 0),
  reason text not null check (length(trim(reason)) between 3 and 500),
  sale_id bigint references public.sales(id),
  responsible_id uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);
create index if not exists cash_movements_session_created_idx on public.cash_movements(session_id, created_at);

create table if not exists public.store_settings (
  setting_key text primary key check (setting_key = 'general'),
  settings jsonb not null default '{}'::jsonb,
  updated_by uuid not null references auth.users(id),
  updated_at timestamptz not null default now()
);

alter table public.inventory_movements add column if not exists supplier_id bigint references public.suppliers(id);
alter table public.inventory_movements add column if not exists receipt_id bigint references public.purchase_receipts(id);

alter table public.suppliers enable row level security;
alter table public.supplier_products enable row level security;
alter table public.purchase_receipts enable row level security;
alter table public.purchase_receipt_items enable row level security;
alter table public.cash_sessions enable row level security;
alter table public.sale_payments enable row level security;
alter table public.cash_movements enable row level security;
alter table public.store_settings enable row level security;
revoke all on table public.suppliers, public.supplier_products, public.purchase_receipts, public.purchase_receipt_items,
  public.cash_sessions, public.sale_payments, public.cash_movements, public.store_settings from anon, authenticated;

-- Crea un producto del mismo catálogo público y su variante inicial de forma atómica.
-- La columna FK se detecta desde los catálogos de PostgreSQL porque el esquema original no
-- documenta el nombre del campo products -> sports.
create or replace function public.create_admin_product(
  p_name text, p_description text, p_price numeric, p_sport_slug text, p_image_url text,
  p_sku text, p_size text, p_color text, p_initial_stock integer, p_minimum integer, p_responsible_id uuid
) returns table (product_id integer, variant_id integer)
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_sport_column text;
  v_product_id integer;
  v_variant_id integer;
begin
  if p_responsible_id is null or length(trim(coalesce(p_name, ''))) not between 2 and 200
     or length(coalesce(p_description, '')) > 4000 or p_price is null or p_price <= 0 or p_price > 100000000
     or length(trim(coalesce(p_sport_slug, ''))) not between 1 and 80
     or length(coalesce(p_image_url, '')) > 1000 or length(coalesce(p_sku, '')) > 100
     or length(trim(coalesce(p_size, ''))) not between 1 and 40 or length(coalesce(p_color, '')) > 60
     or p_initial_stock is null or p_initial_stock < 0 or p_initial_stock > 100000
     or p_minimum is null or p_minimum < 0 or p_minimum > 100000 then
    raise exception 'Datos de producto o variante inválidos' using errcode = '22023';
  end if;
  select a.attname into v_sport_column
    from pg_constraint c
    cross join lateral unnest(c.conkey) as key_column(attnum)
    join pg_attribute a on a.attrelid = c.conrelid and a.attnum = key_column.attnum
   where c.contype = 'f' and c.conrelid = 'public.products'::regclass
     and c.confrelid = 'public.sports'::regclass
   limit 1;
  if v_sport_column is null then
    raise exception 'No se encontró una relación products-sports; verificá el esquema de Supabase' using errcode = '42P01';
  end if;
  if not exists (select 1 from public.sports where slug = trim(p_sport_slug)) then
    raise exception 'El deporte no existe' using errcode = '23503';
  end if;
  if p_sku is not null and length(trim(p_sku)) > 0 and exists (select 1 from public.products where lower(sku) = lower(trim(p_sku))) then
    raise exception 'El SKU ya está en uso' using errcode = '23505';
  end if;
  execute format(
    'insert into public.products(nombre, descripcion, precio, imagen_url, activo, sku, %I)
     select $1, $2, $3, $4, true, nullif($5, ''''), id from public.sports where slug = $6 returning id',
    v_sport_column
  ) into v_product_id using trim(p_name), coalesce(p_description, ''), p_price, coalesce(p_image_url, ''), p_sku, trim(p_sport_slug);
  if v_product_id is null then raise exception 'No se pudo asociar el producto al deporte' using errcode = '23503'; end if;
  select variant_id into v_variant_id from public.create_product_variant(
    v_product_id, trim(p_size), p_initial_stock, p_minimum, p_responsible_id
  );
  if nullif(trim(coalesce(p_color, '')), '') is not null then
    update public.product_variants set color = trim(p_color) where id = v_variant_id;
  end if;
  return query select v_product_id, v_variant_id;
end;
$$;

create or replace function public.create_product_variant_color(
  p_product_id integer, p_size text, p_color text, p_initial_stock integer, p_minimum integer, p_responsible_id uuid
) returns table (variant_id integer, stock_after integer)
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_variant_id integer; v_stock integer := 0;
begin
  if p_product_id is null or p_responsible_id is null or length(trim(coalesce(p_size, ''))) not between 1 and 40
     or length(coalesce(p_color, '')) > 60 or p_initial_stock is null or p_initial_stock < 0 or p_initial_stock > 100000
     or p_minimum is null or p_minimum < 0 or p_minimum > 100000 then
    raise exception 'Variante o existencias iniciales inválidas' using errcode = '22023';
  end if;
  perform 1 from public.products where id = p_product_id and activo = true for update;
  if not found then raise exception 'Producto inexistente o inactivo' using errcode = 'P0002'; end if;
  if exists (select 1 from public.product_variants where product_id = p_product_id and lower(talle) = lower(trim(p_size)) and lower(color) = lower(trim(coalesce(p_color, '')))) then
    raise exception 'La combinación de talle y color ya existe' using errcode = '23505';
  end if;
  insert into public.product_variants(product_id, talle, color, stock, stock_minimo)
  values (p_product_id, trim(p_size), trim(coalesce(p_color, '')), 0, p_minimum) returning id into v_variant_id;
  if p_initial_stock > 0 then
    select movement.stock_after into v_stock from public.register_inventory_movement(v_variant_id, p_initial_stock, 'Stock inicial', p_responsible_id) as movement;
  end if;
  return query select v_variant_id, v_stock;
end;
$$;

create or replace function public.open_cash_session(p_user_id uuid, p_opening_float numeric)
returns public.cash_sessions language plpgsql security definer set search_path = public, pg_temp as $$
declare v_session public.cash_sessions;
begin
  if p_user_id is null or p_opening_float is null or p_opening_float < 0 or p_opening_float > 1000000000 then
    raise exception 'Saldo inicial inválido' using errcode = '22023';
  end if;
  insert into public.cash_sessions(opened_by, opening_float) values (p_user_id, p_opening_float) returning * into v_session;
  return v_session;
end;
$$;

create or replace function public.register_cash_movement(p_session_id bigint, p_kind text, p_amount numeric, p_reason text, p_user_id uuid)
returns public.cash_movements language plpgsql security definer set search_path = public, pg_temp as $$
declare v_movement public.cash_movements;
begin
  if p_session_id is null or p_kind not in ('entrada', 'retiro') or p_amount is null or p_amount <= 0 or p_amount > 1000000000
     or p_user_id is null or length(trim(coalesce(p_reason, ''))) not between 3 and 500 then
    raise exception 'Movimiento de caja inválido' using errcode = '22023';
  end if;
  perform 1 from public.cash_sessions where id = p_session_id and status = 'abierta' for update;
  if not found then raise exception 'La caja no está abierta' using errcode = '23514'; end if;
  insert into public.cash_movements(session_id, kind, amount, reason, responsible_id)
  values (p_session_id, p_kind, p_amount, trim(p_reason), p_user_id) returning * into v_movement;
  return v_movement;
end;
$$;

create or replace function public.close_cash_session(p_session_id bigint, p_user_id uuid, p_counted_cash numeric)
returns public.cash_sessions language plpgsql security definer set search_path = public, pg_temp as $$
declare v_session public.cash_sessions; v_expected numeric(12,2);
begin
  if p_session_id is null or p_user_id is null or p_counted_cash is null or p_counted_cash < 0 or p_counted_cash > 1000000000 then
    raise exception 'Cierre de caja inválido' using errcode = '22023';
  end if;
  select * into v_session from public.cash_sessions where id = p_session_id and status = 'abierta' for update;
  if not found then raise exception 'La caja no está abierta' using errcode = '23514'; end if;
  select v_session.opening_float
    + coalesce((select sum(p.amount) from public.sales s join public.sale_payments p on p.sale_id = s.id where s.cash_session_id = p_session_id and s.status = 'completada' and p.method = 'efectivo'), 0)
    + coalesce((select sum(case when m.kind = 'entrada' then m.amount else -m.amount end) from public.cash_movements m where m.session_id = p_session_id), 0)
    into v_expected;
  update public.cash_sessions set status = 'cerrada', closed_by = p_user_id, closed_at = now(),
    expected_cash = v_expected, counted_cash = p_counted_cash, difference = p_counted_cash - v_expected
   where id = p_session_id returning * into v_session;
  return v_session;
end;
$$;

create or replace function public.register_purchase_receipt(p_supplier_id bigint, p_reference text, p_notes text, p_user_id uuid, p_items jsonb)
returns table (receipt_id bigint, item_count integer) language plpgsql security definer set search_path = public, pg_temp as $$
declare v_receipt_id bigint; v_item record; v_before integer; v_after integer; v_count integer := 0;
begin
  if p_supplier_id is null or p_user_id is null or jsonb_typeof(p_items) is distinct from 'array'
     or jsonb_array_length(p_items) not between 1 and 100 or length(coalesce(p_reference, '')) > 120 or length(coalesce(p_notes, '')) > 1000 then
    raise exception 'Reposición inválida' using errcode = '22023';
  end if;
  perform 1 from public.suppliers where id = p_supplier_id and activo = true for update;
  if not found then raise exception 'Proveedor inexistente o inactivo' using errcode = 'P0002'; end if;
  insert into public.purchase_receipts(supplier_id, reference, notes, responsible_id)
  values (p_supplier_id, coalesce(trim(p_reference), ''), coalesce(trim(p_notes), ''), p_user_id) returning id into v_receipt_id;
  for v_item in select variant_id, quantity, unit_cost from jsonb_to_recordset(p_items) as x(variant_id integer, quantity integer, unit_cost numeric) order by variant_id
  loop
    if v_item.variant_id is null or v_item.quantity is null or v_item.quantity < 1 or v_item.quantity > 100000 or v_item.unit_cost is null or v_item.unit_cost < 0 then
      raise exception 'Línea de reposición inválida' using errcode = '22023';
    end if;
    select stock into v_before from public.product_variants where id = v_item.variant_id for update;
    if not found then raise exception 'Variante inexistente' using errcode = 'P0002'; end if;
    v_after := v_before + v_item.quantity;
    update public.product_variants set stock = v_after where id = v_item.variant_id;
    insert into public.purchase_receipt_items(receipt_id, variant_id, quantity, unit_cost) values (v_receipt_id, v_item.variant_id, v_item.quantity, v_item.unit_cost);
    insert into public.inventory_movements(variant_id, cantidad, motivo, responsable_id, stock_anterior, stock_actual, supplier_id, receipt_id)
    values (v_item.variant_id, v_item.quantity, 'Reposición ' || coalesce(trim(p_reference), '#' || v_receipt_id), p_user_id, v_before, v_after, p_supplier_id, v_receipt_id);
    v_count := v_count + 1;
  end loop;
  return query select v_receipt_id, v_count;
end;
$$;

